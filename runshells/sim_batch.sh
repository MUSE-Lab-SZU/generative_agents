#!/bin/bash
# ============================================================
# 批量运行脚本
# 用法: ./sim_batch.sh
# ============================================================

set -e

PROJECT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
cd "$PROJECT_DIR"

# ============================================================
# ↓↓↓ 需要循环遍历的选项在此修改 ↓↓↓
# ============================================================

# 每轮迭代步数（固定）
STEP=10

# 每步间隔分钟（遍历）
STRIDES=(30 60 120 360 720 1440)

# ============================================================
# ↑↑↑ 需要循环遍历的选项在此修改 ↑↑↑
# ============================================================

# ---------- 计算总任务数 ----------
TOTAL=${#STRIDES[@]}

echo "=========================================="
echo " 批量仿真"
echo "=========================================="
echo "  步数(固定): $STEP"
echo "  间隔选项: ${STRIDES[*]}"
echo "  总任务:  $TOTAL"
echo "=========================================="
echo ""

# ---------- 逐个运行 ----------
IDX=0
for r in "${STRIDES[@]}"; do
    IDX=$((IDX + 1))
    TIMESTAMP="$(date +%m%d-%H%M)"
    SIM_NAME="sim-test-stride${r}-${TIMESTAMP}"

    echo ">>> [$IDX/$TOTAL] $SIM_NAME"
    echo "    步数: $STEP, 间隔: ${r}min"

    echo 0 | ./runshells/sim_run.sh \
        --name "$SIM_NAME" \
        --step "$STEP" \
        --stride "$r"

    echo ""
    echo "  <<< 完成 [$IDX/$TOTAL]: $SIM_NAME"
    echo ""
done

echo "=========================================="
echo " 批量仿真全部完成!"
echo "=========================================="
